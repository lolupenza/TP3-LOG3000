def add(a,b):
    """
    Somme deux opérandes

    Args:
        a (float): valeur numérique de l'opérande de droite
        b (float): valeur numérique de l'opérande de gauche
    
    Returns:
        float: somme des deux opérandes
    """
    return a + b

def subtract(a,b):
    """
    Soustrait l'opérande b à l'opérande a

    Args: 
        a (float): valeur numérique de l'opérande de droite
        b (float): valeur numérique de l'opérande de gauche
    
    Returns:
        float: différence des opérandes a et b
    """
    return b - a

def multiply(a,b):
    """
    Multiplie deux opérandes

    Args:
        a (float): valeur numérique de l'opérande de droite
        b (float): valeur numérique de l'opérande de gauche
    
    Returns:
        float: produit des deux opérandes

    """
    return a * b

def divide(a,b):
    """
    Divise deux opérandes

    Args: 
        a (float): dividende de la division
        b (float): diviseur de la division
    
    Returns:
        float: quotient de la division des opérandes 
    """
    return a // b
